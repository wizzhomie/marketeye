"""A tiny local "competitor shop" for the live example.

It is a real HTTP server on 127.0.0.1 (default port 8768), so the collector
fetches it the same way it fetches any other site. Its price changes between
checks, which is what makes a price move visible without touching a real
retailer.

The price is deterministic: a small sequence advanced by the collector, not by
the clock, so a demo can be repeated exactly.
"""

from __future__ import annotations

import json
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STATE_PATH = ROOT / "data" / "demo-shop.json"

PRODUCT = "Portland cement M500, 50 kg"
PRICE_SEQUENCE = [370, 349, 365, 335, 359, 341, 329, 355, 349, 335]
STATE_LOCK = threading.Lock()


def _read_state() -> dict:
    try:
        data = json.loads(STATE_PATH.read_text(encoding="utf-8"))
        tick = int(data.get("tick", 0))
    except (OSError, ValueError, TypeError):
        tick = 0
    return {"tick": max(0, tick)}


def state() -> dict:
    with STATE_LOCK:
        return _read_state()


def current_price() -> int:
    tick = state()["tick"]
    return PRICE_SEQUENCE[tick % len(PRICE_SEQUENCE)]


def advance_tick() -> int:
    """Move the shop to the next day's price; the collector calls this."""
    with STATE_LOCK:
        tick = _read_state()["tick"] + 1
        STATE_PATH.parent.mkdir(parents=True, exist_ok=True)
        STATE_PATH.write_text(json.dumps({"tick": tick}), encoding="utf-8")
    return tick % len(PRICE_SEQUENCE)


def reset() -> None:
    with STATE_LOCK:
        STATE_PATH.unlink(missing_ok=True)


def render_page() -> str:
    price = current_price()
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
  <title>{PRODUCT} — Demo Build Supply</title>
  <style>
    body {{ margin: 0; padding: 40px 24px; background: #f6f4ee; color: #1d1b16;
      font: 15px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }}
    main {{ max-width: 560px; margin: 0 auto; }}
    nav {{ font-size: 13px; color: #7a7468; margin-bottom: 26px; }}
    h1 {{ margin: 0 0 6px; font-size: 26px; letter-spacing: -0.02em; }}
    .sku {{ margin: 0 0 22px; font-size: 13px; color: #7a7468; }}
    .price {{ margin: 0 0 6px; font-size: 34px; font-weight: 600; letter-spacing: -0.03em; }}
    .unit {{ font-size: 13px; color: #7a7468; }}
    .note {{ margin-top: 26px; padding-top: 16px; border-top: 1px solid #e4dfd3;
      font-size: 12px; color: #7a7468; }}
    a {{ color: inherit; }}
  </style>
</head>
<body>
  <main>
    <nav>Demo Build Supply · Building materials</nav>
    <h1>{PRODUCT}</h1>
    <p class="sku">SKU DEMO-CEM-500 · in stock</p>
    <p class="price">{price} RUB</p>
    <p class="unit">per 50 kg bag, retail</p>
    <p class="note">Demo competitor page. The price is generated by the MarketEye
    demo and changes between collections.</p>
  </main>
</body>
</html>
"""


class _Handler(BaseHTTPRequestHandler):
    server_version = "DemoShop/0.1"

    def do_GET(self) -> None:  # noqa: N802 - stdlib naming
        if self.path.split("?")[0] in ("/", "/cement", "/cement/"):
            body = render_page().encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return
        self.send_error(404, "Not found")

    def log_message(self, fmt: str, *args: object) -> None:
        return


def start(port: int = 8768) -> ThreadingHTTPServer:
    server = ThreadingHTTPServer(("127.0.0.1", port), _Handler)
    thread = threading.Thread(target=server.serve_forever, name="demo-shop", daemon=True)
    thread.start()
    return server
